create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null unique check (char_length(nickname) between 2 and 14),
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_questions (
  id integer generated by default as identity primary key,
  question text not null,
  options jsonb not null,
  correct_index integer not null check (correct_index between 0 and 3),
  explanation text not null,
  source_name text not null,
  source_url text not null,
  active boolean not null default true
);

create table if not exists public.quiz_results (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  score integer not null check (score between 0 and 100),
  correct_count integer not null,
  total_count integer not null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.quiz_results enable row level security;

-- 브라우저에서 직접 프로필/정답/점수를 수정하지 못하게 막습니다.
revoke all on public.profiles from anon, authenticated;
revoke all on public.quiz_questions from anon, authenticated;
revoke all on public.quiz_results from anon, authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
declare desired_nickname text;
begin
  desired_nickname := coalesce(new.raw_user_meta_data->>'nickname', '참가자');
  insert into public.profiles(id, nickname)
  values(new.id, desired_nickname);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- 문제만 내려주고 정답 인덱스는 내려주지 않습니다.
create or replace function public.get_quiz_questions()
returns jsonb language plpgsql security definer set search_path = public
as $$
declare result jsonb;
begin
  if auth.uid() is null then raise exception '로그인이 필요합니다.'; end if;
  select jsonb_agg(jsonb_build_object(
    'id', q.id, 'question', q.question, 'options', q.options,
    'explanation', q.explanation, 'source_name', q.source_name, 'source_url', q.source_url
  ))
  into result
  from (select * from public.quiz_questions where active = true order by random() limit 5) q;
  return coalesce(result, '[]'::jsonb);
end;
$$;

-- 제출된 선택지를 DB의 정답과 비교하여 서버에서 채점합니다.
create or replace function public.submit_quiz(p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare
  total integer;
  correct integer;
  calculated_score integer;
  inserted_id bigint;
begin
  if auth.uid() is null then raise exception '로그인이 필요합니다.'; end if;
  if jsonb_typeof(p_answers) <> 'array' then raise exception '답안 형식이 올바르지 않습니다.'; end if;
  total := jsonb_array_length(p_answers);
  if total <> 5 then raise exception '문제 수가 올바르지 않습니다.'; end if;

  select count(*) into correct
  from jsonb_array_elements(p_answers) a
  join public.quiz_questions q on q.id = (a->>'id')::integer
  where q.active = true
    and (a->>'selected') ~ '^[0-3]$'
    and q.correct_index = (a->>'selected')::integer;

  -- 현재 활성 문제 중 5개가 제출됐는지, 중복 ID가 없는지 검사합니다.
  if (select count(distinct (a->>'id')::integer) from jsonb_array_elements(p_answers) a) <> 5 then
    raise exception '중복된 문제가 있습니다.';
  end if;
  if (select count(*) from public.quiz_questions q
      where q.active = true and q.id in
      (select (a->>'id')::integer from jsonb_array_elements(p_answers) a)) <> 5 then
    raise exception '유효하지 않은 문제가 포함되어 있습니다.';
  end if;

  calculated_score := correct * 20;
  insert into public.quiz_results(user_id, score, correct_count, total_count)
  values(auth.uid(), calculated_score, correct, total)
  returning id into inserted_id;

  return jsonb_build_object('result_id', inserted_id, 'score', calculated_score,
    'correct_count', correct, 'total_count', total);
end;
$$;

create or replace function public.get_leaderboard()
returns jsonb language sql security definer set search_path = public
as $$
  select coalesce(jsonb_agg(to_jsonb(r) order by r.best_score desc, r.nickname asc), '[]'::jsonb)
  from (
    select p.id as user_id, p.nickname, max(qr.score) as best_score
    from public.profiles p
    join public.quiz_results qr on qr.user_id = p.id
    group by p.id, p.nickname
    order by max(qr.score) desc, p.nickname asc
    limit 100
  ) r;
$$;

grant execute on function public.get_quiz_questions() to authenticated;
grant execute on function public.submit_quiz(jsonb) to authenticated;
grant execute on function public.get_leaderboard() to anon, authenticated;

